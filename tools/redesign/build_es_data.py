"""Build redesign/assets/js/es-data.js from the mirrored current ES page (mirror/showroom/ES.html)
and its recorded spec API responses, so the redesign shows real colours, features, specs and FAQ.
usage: python3 tools/redesign/build_es_data.py   (run from the repo root)"""
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'mirror/showroom/ES.html'
API = ROOT / 'mirror/_api/xml'
OUT = ROOT / 'redesign/assets/js/es-data.js'

h = SRC.read_text(encoding='utf-8')


def obj_at(i):
    depth = 0
    for j in range(i, len(h)):
        if h[j] == '{':
            depth += 1
        elif h[j] == '}':
            depth -= 1
            if depth == 0:
                return json.loads(h[i:j + 1])
    raise ValueError(i)


def first(key):
    return obj_at(h.find(key))


def img(p):
    # mirror page paths are relative to mirror/showroom/; redesign pages live in redesign/showroom/
    return ('../../mirror/showroom/' + p) if p and not p.startswith('http') else p


def clean(s):
    return html.unescape(s or '').replace('\r\n', '\n').strip()


colors = first('{"type":"colors"')['content']['data']
exterior = [{'name': clean(c['cname']).split('\n')[0], 'note': '\n'.join(clean(c['cname']).split('\n')[1:]).lstrip('*'),
             'code': c['code'], 'car': img(c['car']),
             'spin': (c['360']['folder'] + c['360']['filename']) if c.get('360') else ''} for c in colors[0]['colors']]


def photos(kind):
    i = h.find(f'"type":"{kind}","photos"')
    if i < 0:
        i = h.find(f'"type":"{kind}","note"')
    o = obj_at(h.rfind('{"dark"', 0, i))
    return [{'name': clean(p['name']), 'image': img(p['image']), 'models': p.get('carmodel', '').split(',')}
            for p in o['photos'] if p.get('name')]


features = {}
i = h.find('{"type":"feature"')
while i >= 0:
    o = obj_at(i)
    features[o['name']] = {'label': o['cname'], 'items': [
        {'title': clean(p['title']).split('\n')[-1], 'desc': clean(re.sub(r'<[^>]+>', '', p.get('desc', ''))),
         'note': clean(p.get('note')), 'image': img(p['image']), 'models': p.get('carmodel', '').split(',')}
        for p in o.get('popup', [])]}
    i = h.find('{"type":"feature"', i + 10)

specs = first('{"type":"specs"')['content']
values = {}
for f in API.glob('carspec_xml.ashx__c1=*&typ=1.txt'):
    cid = int(re.search(r'c1=(\d+)', f.name).group(1))
    values[cid] = {r['boo']: clean(r['val']).replace('<br />', '\n') for r in json.loads(f.read_text(encoding='utf-8-sig'))}
cars = [{'name': c['name'], 'id': int(c['value'])} for c in specs['cars'] if int(c['value']) in values]
table, manuals = [], {}
for t_i, t in enumerate(specs['table'], 1):
    if t['type'] in ('manual', 'bluetooth'):
        manuals[t['type']] = [{'title': clean(m['title']), 'link': m['link']} for m in t['list']]
        continue
    for c_i, cat in enumerate(t['list'], 1):
        rows = []
        for r_i, item in enumerate(cat['items'], 1):
            code = f'{t_i:02d}{c_i:02d}{r_i:02d}'
            rows.append({'label': clean(item), 'values': {str(c['id']): values[c['id']].get(code, '-') for c in cars}})
        table.append({'kind': t['type'], 'category': clean(cat['category']), 'rows': rows})

faq = [{'category': clean(c['category']), 'list': [{'q': clean(q['question']), 'a': q['answer']} for q in c['list']]}
       for c in first('{"type":"faq"')['content']['data']]

data = {'exterior': exterior, 'interior': photos('interior'), 'trim': photos('trim'), 'rim': photos('rim'),
        'features': features, 'specCars': cars, 'specTable': table, 'manuals': manuals, 'faq': faq}
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text('/* generated by tools/redesign/build_es_data.py from mirror/showroom/ES.html — do not edit */\nwindow.ES_DATA = '
               + json.dumps(data, ensure_ascii=False, indent=1) + ';\n', encoding='utf-8')
print('exterior', len(exterior), 'interior', len(data['interior']), 'trim', len(data['trim']), 'rim', len(data['rim']))
print('features', {k: len(v['items']) for k, v in features.items()})
print('spec cars', [c['name'] for c in cars], 'categories', len(table), 'rows', sum(len(t['rows']) for t in table))
print('faq', [(c['category'], len(c['list'])) for c in faq])
